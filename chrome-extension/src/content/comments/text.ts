/** Нормализация: нижний регистр + ё→е (для совпадений «стёкла/стекла»). */
export function normalizeToken(token: string): string {
  return token.toLowerCase().replace(/ё/gu, "е");
}

/**
 * Разбить текст на слова-токены (кириллица, латиница, цифры, дефисы).
 * Стоп-слова и однобуквенные выбрасываются; цифровые токены сохраняются
 * (номера моделей «15», объём «128»).
 */
export function tokenize(text: string): string[] {
  const words = (text.toLowerCase().replace(/ё/gu, "е").match(/[\p{L}\p{N}-]+/gu) ?? [])
    .map((w) => w.replace(/-+$/u, ""))
    .filter((w) => /[\p{L}\p{N}]/u.test(w));
  const out: string[] = [];
  for (const w of words) {
    const t = w.length > 1 && !STOPWORDS.has(w) ? w : "";
    if (t) out.push(t);
  }
  return out;
}

/** Окончания русского слова для лёгкого стемминга (от длинных к коротким). */
const RU_ENDINGS = [
  "ыми", "ями", "ами", "ого", "ему", "оме", "ове", "ами", "оего",
  "ими", "ыми", "его", "ому", "иее", "ий", "ый", "ой", "ей", "ом",
  "ем", "ах", "ях", "ов", "ев", "ам", "ям", "ую", "юю", "ая", "яя",
  "ое", "ee", "ие", "ые", "ыи", "ии", "а", "я", "о", "е", "у", "ю",
  "ы", "и", "ь",
];

/** Лёгкий русский стеммер (суффиксальный, 1 проход). */
export function stem(word: string): string {
  const w = normalizeToken(word);
  if (w.length <= 4) return w;
  for (const end of RU_ENDINGS) {
    if (w.length - end.length >= 3 && w.endsWith(end)) {
      return w.slice(0, w.length - end.length);
    }
  }
  return w;
}

/** Токенизация + стемминг: каноническая форма для сравнения корпусов. */
export function tokenizeStemmed(text: string): string[] {
  return tokenize(text).map(stem);
}

/** Многaccетво канонических форм из текста (для индексов). */
export function stemSet(text: string): Set<string> {
  return new Set(tokenizeStemmed(text));
}

/**
 * Кириллические глифы-омонимы латинских букв (пользователи пишут «17е»/«17e»,
 * «3D»/«3д»). Нужны только для имён моделей (цифровой префикс), чтобы
 * «17е» совпадало с «17e» в корпусе паспорта.
 */
const CYR_TO_LATIN: Record<string, string> = {
  "а": "a", "е": "e", "ё": "e", "о": "o", "с": "c", "р": "p",
  "х": "x", "к": "k", "м": "m", "в": "b", "т": "t", "у": "y", "н": "h",
};

/**
 * Варианты стема для токенов с цифровым префиксом (имя модели): обычный стем +
 * латинская транслитерация глифов-омонимов. «17е» → ['17е', '17e'].
 */
export function productStems(tok: string): string[] {
  const st = stem(tok);
  if (!/^[0-9]/u.test(st)) return [st];
  let lat = "";
  for (const ch of st) {
    lat += CYR_TO_LATIN[ch] ?? ch;
  }
  return lat && lat !== st ? [st, lat] : [st];
}
